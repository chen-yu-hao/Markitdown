  const done=()=>page.getByRole('button',{name:'Finish node editing',exact:true}).click();
  const panel=()=>page.getByRole('dialog',{name:'Table editor',exact:true});
  const formula=()=>page.getByRole('dialog',{name:'Equation editor',exact:true});
  const editorCell=()=>page.locator('.markedown-editor .md-rendered table tbody td').first();
  await editorCell().click();await panel().waitFor();
  await page.getByRole('textbox',{name:'Cell A2',exact:true}).fill('中文 é 😀 | added');await settle();
